function slugName(name = "") {
  return String(name)
    .split("/")
    .at(0)
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function aliasesForName(name) {
  return String(name)
    .split("/")
    .map((item) => item.trim())
    .filter(Boolean);
}

function buildCatalog(prefix, label, names, { defaultZoneId = "adventure", heatBase = 8800 } = {}) {
  return names.map((name, index) => ({
    id: `oneclick_${prefix}_${String(index + 1).padStart(3, "0")}_${slugName(name) || "ip"}`,
    name,
    aliases: aliasesForName(name),
    defaultZoneId,
    heatScore: Math.max(6200, heatBase - index * 9),
    tags: [label, "一键IP入池", "待权利核验"],
    description: `${label}方向的一键 IP 入池候选：${name}。先建立 IP 资产条目，角色目录可通过后续深挖补全。`,
  }));
}

