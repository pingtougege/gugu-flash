export function validateBackendAlphaRouteCoverage() {
  const errors = [];
  const contractIds = new Set(FLASH_API_ROUTES.map((route) => route.id));

  for (const routeId of BACKEND_ALPHA_ROUTE_IDS) {
    if (!contractIds.has(routeId)) errors.push(`Backend Alpha route ${routeId} is not in FLASH_API_ROUTES`);
  }

  for (const route of FLASH_API_ROUTES) {
    if (!BACKEND_ALPHA_ROUTE_IDS.has(route.id)) errors.push(`${route.id} is not covered by Backend Alpha route table`);
  }

  for (const [methodName, routeId] of Object.entries(MOCK_FLASH_API_METHOD_ROUTES)) {
    if (!BACKEND_ALPHA_ROUTE_IDS.has(routeId)) errors.push(`Mock method ${methodName} maps to uncovered Backend Alpha route ${routeId}`);
  }

  return errors;
}
